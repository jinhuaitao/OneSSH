export function countryOf(code) {
    return BY_CODE.get(String(code || '').toUpperCase()) || null;
}

export function countryName(code) {
    const c = countryOf(code);
    return c ? c.n : '未标注地区';
}

export function flagOf(code) {
    const c = countryOf(code);
    return c ? c.f : '🌐';
}

