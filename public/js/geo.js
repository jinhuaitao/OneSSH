const norm = (s) => String(s || '').toLowerCase().replace(/[\s\-_.·]/g, '');

const CITY_INDEX = new Map();
for (const c of CITIES) {
    CITY_INDEX.set(norm(c.n), c);
}

export function findCity(name) {
    const key = norm(name);
    if (!key) return null;
    if (CITY_INDEX.has(key)) return CITY_INDEX.get(key);
    // 允许 "东京 Tokyo" 之类的输入：取第一个能命中的片段
    for (const part of String(name).split(/[\s,，/|]+/)) {
        const hit = CITY_INDEX.get(norm(part));
        if (hit) return hit;
    }
    return null;
}

/**
 * Resolve a host record to a globe position.
 * City wins over country (it is more precise), country is the fallback.
 */
export function locate(host) {
    const cityName = String((host && host.city) || '').trim();
    const cc = String((host && host.country) || '').toUpperCase();
    const hit = cityName ? findCity(cityName) : null;
    if (hit) return { lat: hit.lat, lon: hit.lon, city: hit.n, cc: cc || hit.c };
    const co = countryOf(cc);
    if (co) return { lat: co.lat, lon: co.lon, city: cityName || co.city, cc: co.c };
    if (cityName) return null;
    return null;
}

export function regionLabel(host) {
    const cc = String((host && host.country) || '').toUpperCase();
    const city = String((host && host.city) || '').trim();
    const co = countryOf(cc);
    if (co && city) return co.n + ' · ' + city;
    if (co) return co.n;
    if (city) return city;
    return '未标注地区';
}
